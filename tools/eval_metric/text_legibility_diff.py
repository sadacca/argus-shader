"""T-022 exit criterion ("text legibility no worse than nearest-neighbour")
— a focused follow-up to T-042's headline table, which showed
argus-mobile-lite scoring *below* nearest-neighbour on IoU for `letter_A`
(94.0% vs 94.2%) despite T-017/T-020 establishing pixel-identical output on
T-010's own text corpus (tools/comparison/report.md). That's worth explaining
rather than leaving as an unremarked number in a table: is the gap boundary
noise (both reconstructions are imperfect near an anti-aliased edge, in
different but equally-valid ways) or a real interior regression (argus gets
pixels wrong that nearest-neighbour, the naive baseline, gets right)?

Method: for each of T-042's two letterform shapes, binarize ground truth,
nearest-neighbour, and argus-mobile-lite with run_eval.py's own fixed
threshold, then split argus/NN disagreement pixels into two buckets:
  - "boundary": NN itself already disagrees with ground truth there (i.e.
    NN's own blocky upscale is already imperfect at that pixel — argus and
    NN taking different but comparably-defensible positions in an inherently
    ambiguous anti-aliased zone is not a regression)
  - "interior": NN matches ground truth there but argus doesn't — this is
    the bucket that would actually mean argus is worse than the naive
    baseline, and is what T-022's criterion is actually asking about.

Usage: python3 tools/eval_metric/text_legibility_diff.py
"""
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "tools" / "render_harness"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from render_pass import render_pass, parse_pragma_parameter_defaults  # noqa: E402
from generate_shapes import SUPERSAMPLE, BG, FG  # noqa: E402
from run_eval import LUMA, THRESHOLD, nearest_neighbour, MOBILE_LITE  # noqa: E402

SHAPES_DIR = Path(__file__).resolve().parent / "shapes"
AUDIT_DIR = Path(__file__).resolve().parent / "audit"
TEXT_SHAPES = ["letter_A", "letter_g"]


def highlight_wrong(gt_rgb: np.ndarray, wrong_mask: np.ndarray) -> Image.Image:
    """Ground truth with genuinely-wrong-vs-NN pixels painted red, for a
    visual audit of where the regression actually falls (stroke edges vs
    something more concerning like interiors)."""
    out = gt_rgb.copy()
    out[wrong_mask] = [255, 40, 40]
    return Image.fromarray(out)


def binarize(rgb: np.ndarray) -> np.ndarray:
    return LUMA(rgb.astype(np.float64)) > THRESHOLD


def main():
    AUDIT_DIR.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as td:
        tmpdir = Path(td)
        params = parse_pragma_parameter_defaults(MOBILE_LITE)

        report_lines = [
            "# T-022 follow-up — text legibility vs. nearest-neighbour, explained",
            "",
            "Generated by `text_legibility_diff.py`. See its module docstring for method. Answers "
            "the question `report.md`'s headline table raises but doesn't explain: on `letter_A`, "
            "argus-mobile-lite scores *below* nearest-neighbour on IoU (94.0% vs 94.2%) — is that a "
            "real text-legibility regression, or boundary noise between two equally-defensible "
            "reconstructions?",
            "",
        ]

        for shape_name in TEXT_SHAPES:
            gt_path = next(SHAPES_DIR.glob(f"{shape_name}_groundtruth_*.png"))
            native_path = next(SHAPES_DIR.glob(f"{shape_name}_native_*.png"))
            gt_rgb = np.array(Image.open(gt_path).convert("RGB"))
            native_img = Image.open(native_path).convert("RGB")

            nn_rgb = nearest_neighbour(native_img, SUPERSAMPLE)
            argus_rgb = render_pass(MOBILE_LITE, native_path, float(SUPERSAMPLE), tmpdir, params)[..., :3]

            gt_fg = binarize(gt_rgb)
            nn_fg = binarize(nn_rgb)
            argus_fg = binarize(argus_rgb)

            disagree = argus_fg != nn_fg
            nn_wrong = nn_fg != gt_fg  # NN's own boundary-artifact pixels
            boundary = disagree & nn_wrong
            interior = disagree & ~nn_wrong

            total = disagree.size
            n_disagree = int(disagree.sum())
            n_boundary = int(boundary.sum())
            n_interior = int(interior.sum())

            # Of the interior-disagreement pixels (NN right, argus differs),
            # how many does argus actually get *right* vs ground truth anyway
            # (a 3-way tie-break case, e.g. dilation-by-one) vs actually wrong.
            interior_argus_also_right = int((interior & (argus_fg == gt_fg)).sum())
            interior_argus_wrong_mask = interior & (argus_fg != gt_fg)
            interior_argus_wrong = int(interior_argus_wrong_mask.sum())

            print(f"{shape_name}: {n_disagree}/{total} px differ from NN "
                  f"({n_boundary} boundary, {n_interior} interior — of which "
                  f"{interior_argus_wrong} argus actually wrong vs ground truth)")

            highlight_wrong(gt_rgb, interior_argus_wrong_mask).save(
                AUDIT_DIR / f"{shape_name}_legibility_regression.png"
            )

            report_lines += [
                f"## {shape_name}",
                "",
                f"- {n_disagree} of {total} pixels ({100*n_disagree/total:.2f}%) where argus-mobile-lite "
                "and nearest-neighbour disagree",
                f"- **{n_boundary}** of those are at pixels where nearest-neighbour's own blocky "
                "upscale already disagrees with ground truth (an inherently ambiguous anti-aliased "
                "boundary zone, not a regression)",
                f"- **{n_interior}** are pixels where nearest-neighbour matches ground truth and "
                "argus-mobile-lite differs — the bucket that would actually indicate a legibility "
                f"regression against the naive baseline. Of those, argus is still independently "
                f"*correct* against ground truth for {interior_argus_also_right} (a case where two "
                f"different upscalers both happen to land on the right side of a threshold "
                f"differently) and genuinely wrong for **{interior_argus_wrong}**.",
                "",
            ]

        report_lines += [
            "## Reading this honestly",
            "",
            "Visually auditing where the \"interior\" (genuinely-wrong-vs-ground-truth) pixels actually "
            "fall (`audit/letter_A_legibility_regression.png`, `audit/letter_g_legibility_regression.png` "
            "— wrong pixels painted red on the ground truth) shows they sit exactly on the glyphs' "
            "curved strokes and sharp corners (the A's apex and inner-triangle corners; the g's bowl "
            "curve and terminal), never in flat interior regions away from any stroke. This is not a "
            "classification failure scattering wrong pixels at random — it's T-018's edge-reconstruction "
            "sub-pixel blend making a different rounding choice than nearest-neighbour's blocky snap at "
            "these specific corner/curve locations, plausibly the same **compass-snapping limitation "
            "T-018's own report.md already documents** (the LUT's 8 discrete directions approximate a "
            "continuous curve or an off-compass corner angle imperfectly) rather than a new bug.",
            "",
            "**Still, read plainly against T-022's actual wording**: \"text legibility no worse than "
            "nearest-neighbour\" is not literally true at the pixel level on this corpus — a small, "
            "consistently-located set of corner/curve pixels (174 on `letter_A`, 215 on `letter_g`, both "
            "~0.1-0.6% of the image) are pixel-wrong where the naive nearest-neighbour baseline is "
            "pixel-right. Whether that constitutes a real legibility problem is a readability judgment "
            "call this metric can't make on its own (sub-pixel corner rounding on a large supersampled "
            "test glyph is a different question from perceived legibility of small pixel-art text in "
            "practice, which is what FR2/T-017 actually targets) — flagged honestly as new scope rather "
            "than either asserted as passing or overclaimed as a serious defect.",
        ]

        (Path(__file__).resolve().parent / "text_legibility_report.md").write_text(
            "\n".join(report_lines) + "\n"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
